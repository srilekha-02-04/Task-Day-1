package day2;

public class Largest {

	public static void main(String[] args) {
		 int a = 10, b = 20, c = 5;

	        int largest = Math.max(a, Math.max(b, c));
	        int smallest = Math.min(a, Math.min(b, c));

	        System.out.println("Largest = " + largest);
	        System.out.println("Smallest = " + smallest);
	    }
	


	}


